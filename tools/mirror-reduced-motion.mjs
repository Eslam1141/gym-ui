// Keeps the html[data-reduce-motion="1"] mirror in motion.css in sync with
// the real prefers-reduced-motion rules (the Android shell sets the attribute
// when "Remove animations" is on; the WebView ignores that setting for the
// media query). Usage: node tools/mirror-reduced-motion.mjs [--check]
//
// Every `@media (prefers-reduced-motion: reduce) { ... }` block in
// styles.css / motion.css / onboarding.css is copied between the markers at
// the end of motion.css with each selector prefixed by the attribute, plus a
// blanket "no animation, no transition" rule so the `no-preference` blocks
// (which still match under the attribute) cannot run anything.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = ["styles.css", "motion.css", "onboarding.css"];
const BEGIN = "/* >>> reduce-motion mirror (generated by tools/mirror-reduced-motion.mjs; do not edit) */";
const END = "/* <<< reduce-motion mirror */";
const P = 'html[data-reduce-motion="1"]';

function stripComments(s) { return s.replace(/\/\*[\s\S]*?\*\//g, ""); }
function matchBrace(s, open) {
  let d = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === "{") d++;
    else if (s[i] === "}" && --d === 0) return i;
  }
  throw new Error("unbalanced braces");
}
function splitSelectors(sel) {
  const out = []; let d = 0, cur = "";
  for (const ch of sel) {
    if (ch === "(" || ch === "[") d++;
    if (ch === ")" || ch === "]") d--;
    if (ch === "," && d === 0) { out.push(cur.trim()); cur = ""; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}
function prefixSel(sel) {
  if (/^(:root|html)$/.test(sel)) return P;
  if (/^(:root|html)\s/.test(sel)) return P + sel.replace(/^(:root|html)/, "");
  return P + " " + sel;
}
// body = rules inside one reduce block
function mirrorBody(body) {
  let out = "", i = 0;
  while (i < body.length) {
    const o = body.indexOf("{", i);
    if (o < 0) break;
    const sel = body.slice(i, o).trim();
    const c = matchBrace(body, o);
    const decl = body.slice(o + 1, c).trim();
    if (sel.startsWith("@")) throw new Error("nested at-rule in reduce block: " + sel);
    // :hover rules stay inside a hover-capable media query (a repo test enforces it)
    const sels = splitSelectors(sel), hov = sels.filter((x) => /:hover/.test(x)), rest = sels.filter((x) => !/:hover/.test(x));
    if (rest.length) out += rest.map(prefixSel).join(",\n") + "{ " + decl + " }\n";
    if (hov.length) out += "@media (hover:hover){ " + hov.map(prefixSel).join(", ") + "{ " + decl + " } }\n";
    i = c + 1;
  }
  return out;
}

function generate() {
  let out = "";
  for (const f of SOURCES) {
    let src = fs.readFileSync(path.join(root, f), "utf8");
    const bi = src.indexOf(BEGIN);
    if (bi >= 0) src = src.slice(0, bi);
    src = stripComments(src);
    const re = /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{/g;
    let m, chunk = "";
    while ((m = re.exec(src))) {
      const open = m.index + m[0].length - 1;
      const close = matchBrace(src, open);
      chunk += mirrorBody(src.slice(open + 1, close));
      re.lastIndex = close;
    }
    if (chunk) out += "/* from " + f + " */\n" + chunk;
  }
  out += `/* nothing else may run: the no-preference blocks still match under the attribute */
${P} *, ${P} *::before, ${P} *::after{
  animation:none !important; transition:none !important; scroll-behavior:auto !important;
}
/* separate rule: an engine without view transitions would drop the whole list */
${P}::view-transition-group(*), ${P}::view-transition-old(*), ${P}::view-transition-new(*){ animation:none !important; }
`;
  return out;
}

const file = path.join(root, "motion.css");
const cur = fs.readFileSync(file, "utf8");
const bi = cur.indexOf(BEGIN);
const head = (bi >= 0 ? cur.slice(0, bi) : cur.replace(/\s*$/, "\n\n"));
const next = head + BEGIN + "\n" + generate() + END + "\n";
if (process.argv.includes("--check")) {
  if (next !== cur) { console.error("motion.css mirror is stale: run node tools/mirror-reduced-motion.mjs"); process.exit(1); }
  console.log("mirror up to date");
} else {
  fs.writeFileSync(file, next);
  console.log("mirror written (" + generate().split("\n").length + " lines)");
}
